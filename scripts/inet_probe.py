"""Shared driver for the controlled INET scenarios (UavPair / UavSwarm).

All tuning knobs are network-level parameters, so the ini uses single-star
patterns only.  Every measurement run gets its OWN ini file (passed with -f):
the shared omnetpp.ini is regenerated by opp_env on every invocation, which
silently reset sim-time-limit to its default and broke the first version of
the self-test.

Every measurement run is also preceded by a causal self-test: shortening the
send interval 5x must produce ~5x the packets.  A parameter that is silently
ignored cannot pass that.
"""
