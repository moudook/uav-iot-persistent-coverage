def ensure_env():
    subprocess.run(["wsl", "-d", "Ubuntu", "--", "bash", "-c",
                    "mkdir -p /home/gbust/omnetpp_ws/uavsim/traces /home/gbust/omnetpp_ws/uavsim/results"],
                   capture_output=True)
    for f in ("UavPair.ned", "UavSwarm.ned"):
        shutil.copyfile(os.path.join(SRC, f), os.path.join(SCN_UNC, f))


def write_ini(network, params, simtime, seed_set=None, ini_path=None):
    if ini_path is None:
        ini_path = os.path.join(SCN_UNC, f"run_{int(time.time() * 1000)}.ini")
    lines = ["[General]", f"network = {network}", f"sim-time-limit = {simtime}s"]
    if seed_set is not None:
        lines += ["repeat = 100", "seed-set = ${runnumber}", ""]
    for k, v in params.items():
        lines.append(f"*.{k} = {v}")
    lines += ["", "**.scalar-recording = true", "**.vector-recording = false", ""]
    with open(ini_path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    return ini_path


def run_raw(ini_path, runnumber=0):
    ini_wsl = ini_path_wsl(ini_path)
    cmd = (f"cd /home/gbust/omnetpp_ws/uavsim && rm -f results/General-*.sca "
           f"results/General-*.vci results/General-*.vec && "
           f"opp_run -u Cmdenv -f {ini_wsl} -r {runnumber} "
           f"-l /home/gbust/omnetpp_ws/inet-4.6.0/out/clang-release/src/libINET.so "
           f"-n /home/gbust/omnetpp_ws/inet-4.6.0/src:"
           f"/home/gbust/omnetpp_ws/inet-4.6.0/examples:/home/gbust/omnetpp_ws/uavsim")
    full = f"cd /home/gbust/omnetpp_ws && opp_env run inet-4.6.0 -c '{cmd}'"
    r = subprocess.run(["wsl", "-d", "Ubuntu", "--", "bash", "-c", full],
                       capture_output=True, text=True, timeout=1800)
    return r.stdout + r.stderr


def ini_path_wsl(win_path):
    # Convert C:\...\uavsim\foo.ini or \\wsl...\foo.ini to /home/.../uavsim/foo.ini
    name = os.path.basename(win_path)
    return f"/home/gbust/omnetpp_ws/uavsim/{name}"


def parse_sca(network, N, runnumber=0):
    path = os.path.join(SCN_UNC, "results", f"General-#{runnumber}.sca")
    if not os.path.exists(path):
        return None
    sent = [0.0] * N
    recv = [0.0] * N
    pat = re.compile(r'^scalar\s+' + network + r'\.uav\[(\d+)\]\.app\[0\]\s+"([^"]+)"\s+(\S+)')
    with open(path, errors="replace") as f:
        for line in f:
            m = pat.match(line.strip())
            if not m:
                continue
            i, name, val = int(m.group(1)), m.group(2), m.group(3)
            if i >= N:
                continue
            try:
                v = float(val)
            except ValueError:
                continue
            if name == "packets sent":
                sent[i] = v
            elif name == "packets received":
                recv[i] = v
    return sent, recv


def write_trace(name, positions, duration):
    path = os.path.join(SCN_UNC, "traces", name)
    with open(path, "w", newline="\n") as f:
        for (x, y, z) in positions:
            f.write(f"0.00 {x:.3f} {y:.3f} {z:.3f} {duration:.2f} {x:.3f} {y:.3f} {z:.3f}\n")
    return name


_SELF_TESTED = {"done": False, "ok": False}


def self_test():
    if _SELF_TESTED["done"]:
        return _SELF_TESTED["ok"]
    ensure_env()
    write_trace("_selftest.movements", [(0.0, 0.0, 50.0), (30.0, 0.0, 50.0)], 3.0)

    slow, _, out_slow = run_probe("UavPair", 2, "_selftest.movements",
                                  simtime=2.0, sendInterval="0.1s", runnumber=0)
    fast, _, out_fast = run_probe("UavPair", 2, "_selftest.movements",
                                  simtime=2.0, sendInterval="0.02s", runnumber=1)

    ok = False
    reason = ""
    if slow is None or fast is None:
        last = [l for l in (out_slow + out_fast).strip().splitlines() if l.strip()]
        reason = "run failed: " + (last[-1][:120] if last else "?")
    else:
        n_slow, n_fast = sum(slow), sum(fast)
        if n_slow < 5:
            reason = f"baseline sent only {n_slow:.0f} packets"
        elif n_fast < 3.0 * n_slow:
            reason = (f"interval had no effect: {n_slow:.0f} packets at 0.1 s vs "
                      f"{n_fast:.0f} at 0.02 s")
        else:
            ok = True
    if reason:
        print("  self-test:", reason, flush=True)
    _SELF_TESTED["ok"] = ok
    _SELF_TESTED["done"] = True
    return ok


def run_probe(network, N, trace, simtime=20.0, txPower="0.1W", sensitivity="-85dBm",
              snirThreshold="4dB", sendInterval="0.1s", bitrate="6Mbps",
              sigma="6", noise="-94dBm", runnumber=0, extra=None):
    params = {
        "simTrace": f'"traces/{trace}"',
        "simTxPower": txPower,
        "simSensitivity": sensitivity,
        "simSnir": snirThreshold,
        "simInterval": sendInterval,
        "simBitrate": bitrate,
        "simSigma": sigma,
        "simNoise": noise,
    }
    if network == "UavSwarm":
        params["simNumUavs"] = N
    if extra:
        params.update(extra)
    ini_path = write_ini(network, params, simtime, seed_set=runnumber)
    out = run_raw(ini_path, runnumber)
    if "Simulation time limit reached" not in out:
        return None, None, out
    return (*parse_sca(network, N, runnumber), out)
